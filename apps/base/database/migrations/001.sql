CREATE TABLE tenants (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL, status text NOT NULL DEFAULT 'active', deleted_at timestamptz
);
CREATE TABLE sessions (
 id text PRIMARY KEY, tenant_id bigint NOT NULL REFERENCES tenants(id),
 user_id bigint NOT NULL, csrf text NOT NULL,
 last_activity timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL
);
CREATE INDEX sessions_tenant_user_idx ON sessions(tenant_id,user_id);
CREATE TABLE roles (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id), name text NOT NULL,
 grant_all boolean NOT NULL DEFAULT false,
 UNIQUE(tenant_id,id), UNIQUE(tenant_id,name)
);
CREATE TABLE principal_roles (
 tenant_id bigint NOT NULL REFERENCES tenants(id), user_id bigint NOT NULL, role_id bigint NOT NULL,
 PRIMARY KEY(tenant_id,user_id,role_id),
 FOREIGN KEY(tenant_id,role_id) REFERENCES roles(tenant_id,id)
);
CREATE TABLE role_capabilities (
 tenant_id bigint NOT NULL, role_id bigint NOT NULL, capability text NOT NULL,
 PRIMARY KEY(tenant_id,role_id,capability),
 FOREIGN KEY(tenant_id,role_id) REFERENCES roles(tenant_id,id)
);
CREATE TABLE principal_capabilities (
 tenant_id bigint NOT NULL, user_id bigint NOT NULL, capability text NOT NULL, is_allowed boolean NOT NULL,
 PRIMARY KEY(tenant_id,user_id,capability)
);
CREATE TABLE field_restrictions (
 tenant_id bigint NOT NULL, role_id bigint NOT NULL,
 table_id text NOT NULL, field_id text NOT NULL,
 PRIMARY KEY(tenant_id,role_id,table_id,field_id),
 FOREIGN KEY(tenant_id,role_id) REFERENCES roles(tenant_id,id),
 CHECK(table_id='companies' AND field_id IN ('email','phone','tax_id','revenue'))
);
CREATE TABLE authz_decision_log (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id), user_id bigint NOT NULL,
 capability text NOT NULL, allowed boolean NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX authz_decision_log_tenant_idx ON authz_decision_log(tenant_id,created_at);
CREATE TABLE audit_mutations (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id), actor_id bigint NOT NULL,
 auditable_type text NOT NULL, auditable_id bigint NOT NULL,
 old_values jsonb NOT NULL, new_values jsonb NOT NULL,
 trace_id text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_mutations_tenant_record_idx ON audit_mutations(tenant_id,auditable_type,auditable_id);

-- Reference/demo tables for the Grid catalog. Non-business data that lets every
-- Grid slice exercise one-links, many-links, enums, dates and restrictions.
CREATE TABLE base_grid_ref_groups (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id),
 name text NOT NULL CHECK(length(name) BETWEEN 1 AND 160),
 region text NOT NULL CHECK(region IN ('north','south','east','west')),
 UNIQUE(tenant_id,id), UNIQUE(tenant_id,name)
);
CREATE TABLE base_grid_ref_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id),
 group_id bigint NOT NULL,
 name text NOT NULL CHECK(length(name) BETWEEN 1 AND 160),
 category text NOT NULL CHECK(category IN ('tools','parts','supplies')),
 quantity integer NOT NULL DEFAULT 0 CHECK(quantity>=0),
 unit_cost numeric(12,2) NOT NULL DEFAULT 0 CHECK(unit_cost>=0),
 active boolean NOT NULL DEFAULT true,
 UNIQUE(tenant_id,id), UNIQUE(tenant_id,name),
 FOREIGN KEY(tenant_id,group_id) REFERENCES base_grid_ref_groups(tenant_id,id)
);
CREATE TABLE base_grid_ref_movements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id),
 item_id bigint NOT NULL,
 delta integer NOT NULL,
 moved_on date NOT NULL,
 FOREIGN KEY(tenant_id,item_id) REFERENCES base_grid_ref_items(tenant_id,id)
);
CREATE INDEX base_grid_ref_items_group_idx ON base_grid_ref_items(tenant_id,group_id);
CREATE INDEX base_grid_ref_movements_item_idx ON base_grid_ref_movements(tenant_id,item_id,moved_on);

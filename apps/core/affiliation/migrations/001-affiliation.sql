-- Core work contacts; People owns employment and its independent HR dates.
CREATE TABLE person_affiliations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES tenants(id),
    person_id bigint NOT NULL,
    organisation_id bigint NOT NULL,
    title text CHECK (title IS NULL OR length(btrim(title)) BETWEEN 1 AND 160),
    work_email text CHECK (work_email IS NULL OR (octet_length(work_email) BETWEEN 1 AND 254 AND work_email ~ '^[^[:space:]@]+@[^[:space:]@]+$')),
    work_phone text CHECK (work_phone IS NULL OR length(work_phone) BETWEEN 1 AND 64),
    effective_from date CHECK (effective_from BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
    effective_to date CHECK (effective_to BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
    unlinked_at timestamptz,
    version bigint NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, id),
    UNIQUE (tenant_id, id, person_id, organisation_id),
    FOREIGN KEY (tenant_id, person_id) REFERENCES persons(tenant_id, id),
    FOREIGN KEY (tenant_id, organisation_id) REFERENCES companies(tenant_id, id),
    CHECK (effective_to IS NULL OR effective_from IS NULL OR effective_from <= effective_to)
);
-- Deliberately no uniqueness on Person, Organisation, title or work contacts:
-- concurrent affiliations and multiple positions at one company are valid.
CREATE INDEX person_affiliations_person ON person_affiliations(tenant_id, person_id, id);
CREATE INDEX person_affiliations_organisation ON person_affiliations(tenant_id, organisation_id, id);

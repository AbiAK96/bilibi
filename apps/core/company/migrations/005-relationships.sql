-- K5: the dated relationship-role catalog and the directed links from a
-- company to an Organisation or a Person (`apps/core/party/CONTRACT.md`).
-- Bilimbi's compatibility baseline (20260811093956) keeps a global
-- `company_relationship_types` catalog and company-to-company links only;
-- the approved party model makes the catalog tenant-local and lets a link
-- target a Person, so both tables are new and scoped rather than adopted.

-- A role reads from the source company's perspective: `name` is what the
-- target is to the source, `inverse_name` what the source is to the target.
-- Renaming keeps the id and the code; retiring keeps every link that used it.
CREATE TABLE company_relationship_roles (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id),
 code text NOT NULL CHECK(length(code) BETWEEN 1 AND 64),
 name text NOT NULL CHECK(length(btrim(name)) BETWEEN 1 AND 160),
 inverse_name text NOT NULL CHECK(length(btrim(inverse_name)) BETWEEN 1 AND 160),
 retired_on date,
 version bigint NOT NULL DEFAULT 1 CHECK(version >= 1),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(tenant_id, id),
 CONSTRAINT company_relationship_roles_code_unique UNIQUE(tenant_id, code)
);

-- Exactly one target: an organisation of the same tenant (never the source
-- itself) or a person of the same tenant. Direction is always stored; the
-- inverse label is presentation. Dates are inclusive calendar days, both
-- optional. `unlinked_at` retains an unlinked link as dated history.
CREATE TABLE company_relationships (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id),
 source_organisation_id bigint NOT NULL,
 target_organisation_id bigint,
 target_person_id bigint,
 role_id bigint NOT NULL,
 effective_from date,
 effective_to date,
 unlinked_at timestamptz,
 version bigint NOT NULL DEFAULT 1 CHECK(version >= 1),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(tenant_id, id),
 CONSTRAINT company_relationships_source_tenant_foreign FOREIGN KEY(tenant_id, source_organisation_id) REFERENCES companies(tenant_id, id),
 CONSTRAINT company_relationships_target_organisation_tenant_foreign FOREIGN KEY(tenant_id, target_organisation_id) REFERENCES companies(tenant_id, id),
 CONSTRAINT company_relationships_target_person_tenant_foreign FOREIGN KEY(tenant_id, target_person_id) REFERENCES persons(tenant_id, id),
 CONSTRAINT company_relationships_role_tenant_foreign FOREIGN KEY(tenant_id, role_id) REFERENCES company_relationship_roles(tenant_id, id),
 CONSTRAINT company_relationships_one_target CHECK((target_organisation_id IS NULL) <> (target_person_id IS NULL)),
 CONSTRAINT company_relationships_not_self CHECK(target_organisation_id IS NULL OR target_organisation_id <> source_organisation_id),
 CONSTRAINT company_relationships_dates CHECK(effective_from IS NULL OR effective_to IS NULL OR effective_from <= effective_to)
);
CREATE INDEX company_relationships_source_idx ON company_relationships(tenant_id, source_organisation_id, role_id);
CREATE INDEX company_relationships_target_organisation_idx ON company_relationships(tenant_id, target_organisation_id, role_id);
CREATE INDEX company_relationships_target_person_idx ON company_relationships(tenant_id, target_person_id, role_id);
CREATE INDEX company_relationships_dates_idx ON company_relationships(effective_from, effective_to);
-- An exact duplicate assignment (same source, target, role and start) is
-- refused while the earlier one is linked; different roles for one pair and
-- separate dated intervals of one role remain valid.
CREATE UNIQUE INDEX company_relationships_live_unique ON company_relationships(tenant_id, source_organisation_id, coalesce(target_organisation_id, 0), coalesce(target_person_id, 0), role_id, coalesce(effective_from, '0001-01-01'::date)) WHERE unlinked_at IS NULL;

-- Default roles for the tenants that already exist; provisioning and the
-- owner reconcile new tenants by code (`relationship_roles::ensure_defaults`).
INSERT INTO company_relationship_roles(tenant_id, code, name, inverse_name)
SELECT t.id, d.code, d.name, d.inverse_name
FROM tenants t
CROSS JOIN (VALUES ('vendor','Vendor','Customer'), ('customer','Customer','Vendor'), ('prospect','Prospect','Prospective vendor'), ('partner','Partner','Partner')) AS d(code, name, inverse_name)
ON CONFLICT (tenant_id, code) DO NOTHING;

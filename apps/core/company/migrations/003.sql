CREATE TABLE companies (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id),
 name text NOT NULL CHECK(length(name) BETWEEN 1 AND 160),
 status text NOT NULL CHECK(status IN ('active','suspended','pending','archived')),
 email text NOT NULL DEFAULT '', phone text NOT NULL DEFAULT '', tax_id text NOT NULL DEFAULT '',
 revenue bigint NOT NULL DEFAULT 0 CHECK(revenue>=0),
 version bigint NOT NULL DEFAULT 1,
 created_at timestamptz NOT NULL DEFAULT now(), deleted_at timestamptz,
 UNIQUE(tenant_id,id)
);
CREATE INDEX companies_tenant_name_idx ON companies(tenant_id,name,id) WHERE deleted_at IS NULL;

-- K1: the Organisation/company schema on the existing `companies` table and
-- the owned reference tables (Bilimbi compatibility baseline 20260811093956
-- without the Laravel-only columns). Additive: every existing row keeps its
-- id, tenant and URL; new columns default or are backfilled below.
ALTER TABLE companies
 ADD COLUMN parent_id bigint,
 ADD COLUMN code text,
 ADD COLUMN legal_name text,
 ADD COLUMN registration_number text,
 ADD COLUMN legal_entity_type_id bigint,
 ADD COLUMN jurisdiction text,
 ADD COLUMN website text,
 ADD COLUMN scope_activities jsonb,
 ADD COLUMN metadata jsonb,
 ADD COLUMN updated_at timestamptz;

-- Backfill `code` from `name` as Belimbing slugs it (`BlbStr::code`, the
-- Rust `organisation::slug_code`): Latin accents are stripped, dashes and
-- spaces become `_`, `@` becomes `_at_`, other punctuation is dropped. A
-- collision within the tenant, or a name with no ASCII letters, takes the id.
WITH slugged AS (
 SELECT id, tenant_id,
  btrim(regexp_replace(regexp_replace(lower(replace(replace(translate(name,'ÀÁÂÃÄÅàáâãäåÇçÈÉÊËèéêëÌÍÎÏìíîïÑñÒÓÔÕÖØòóôõöøÙÚÛÜùúûüÝýÿŠšŽžĆćČčĐđŁłŚśŹźŻżŃńĘęĄąŐőŰű','AAAAAAaaaaaaCcEEEEeeeeIIIIiiiiNnOOOOOOooooooUUUUuuuuYyySsZzCcCcDdLlSsZzZzNnEeAaOoUu'),'-','_'),'@','_at_')),'[^a-z0-9_[:space:]]+','','g'),'[_[:space:]]+','_','g'),'_') AS slug
 FROM companies WHERE code IS NULL
), numbered AS (
 SELECT id, slug, row_number() OVER (PARTITION BY tenant_id, slug ORDER BY id) AS n FROM slugged
)
UPDATE companies c SET code = CASE WHEN numbered.slug = '' THEN 'company_' || c.id WHEN numbered.n > 1 THEN numbered.slug || '_' || c.id ELSE numbered.slug END
FROM numbered WHERE c.id = numbered.id;

CREATE TABLE company_legal_entity_types (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code text NOT NULL CHECK(length(code) BETWEEN 1 AND 255),
 name text NOT NULL CHECK(length(name) BETWEEN 1 AND 255),
 description text,
 is_active boolean NOT NULL DEFAULT true,
 metadata jsonb,
 version bigint NOT NULL DEFAULT 1,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT company_legal_entity_types_code_unique UNIQUE(code)
);
CREATE INDEX company_legal_entity_types_active_code_idx ON company_legal_entity_types(is_active, code);

CREATE TABLE company_department_types (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code text NOT NULL CHECK(length(code) BETWEEN 1 AND 255),
 name text NOT NULL CHECK(length(name) BETWEEN 1 AND 255),
 category text NOT NULL CHECK(category IN ('administrative','operational','revenue','support')),
 description text,
 is_active boolean NOT NULL DEFAULT true,
 metadata jsonb,
 version bigint NOT NULL DEFAULT 1,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT company_department_types_code_unique UNIQUE(code)
);
CREATE INDEX company_department_types_category_idx ON company_department_types(category);
CREATE INDEX company_department_types_active_category_idx ON company_department_types(is_active, category);

-- A department is one of a company's types. `head_affiliation_id` is the
-- head's affiliation with the company under the approved party model; K18
-- adds the scoped foreign key when `person_affiliations` exists, and no API
-- sets it before then.
CREATE TABLE company_departments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id),
 company_id bigint NOT NULL,
 department_type_id bigint NOT NULL REFERENCES company_department_types(id),
 head_affiliation_id bigint,
 status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','inactive','suspended')),
 metadata jsonb,
 version bigint NOT NULL DEFAULT 1,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(tenant_id, id),
 CONSTRAINT company_departments_company_tenant_foreign FOREIGN KEY(tenant_id, company_id) REFERENCES companies(tenant_id, id),
 CONSTRAINT company_departments_company_type_unique UNIQUE(company_id, department_type_id)
);
CREATE INDEX company_departments_status_idx ON company_departments(status);
CREATE INDEX company_departments_head_idx ON company_departments(head_affiliation_id);

-- The explicit tenant → primary company relationship. Never inferred from a
-- numeric id or the oldest company (Bilimbi `PrimaryCompanyManager`).
CREATE TABLE tenant_primary_companies (
 tenant_id bigint PRIMARY KEY REFERENCES tenants(id),
 company_id bigint NOT NULL,
 CONSTRAINT tenant_primary_companies_company_id_unique UNIQUE(company_id),
 CONSTRAINT tenant_primary_companies_company_tenant_foreign FOREIGN KEY(tenant_id, company_id) REFERENCES companies(tenant_id, id)
);

-- Code is unique within a tenant: Bilimbi's compatibility baseline spans
-- tenants, which would let one tenant learn another's codes.
ALTER TABLE companies
 ALTER COLUMN code SET NOT NULL,
 ADD CONSTRAINT companies_code_length CHECK(length(code) BETWEEN 1 AND 255),
 ADD CONSTRAINT companies_code_unique UNIQUE(tenant_id, code),
 ADD CONSTRAINT companies_parent_tenant_foreign FOREIGN KEY(tenant_id, parent_id) REFERENCES companies(tenant_id, id),
 ADD CONSTRAINT companies_parent_not_self CHECK(parent_id IS NULL OR parent_id <> id),
 ADD CONSTRAINT companies_legal_entity_type_foreign FOREIGN KEY(legal_entity_type_id) REFERENCES company_legal_entity_types(id),
 ADD CONSTRAINT companies_legal_name_length CHECK(legal_name IS NULL OR length(legal_name) BETWEEN 1 AND 255),
 ADD CONSTRAINT companies_registration_number_length CHECK(registration_number IS NULL OR length(registration_number) BETWEEN 1 AND 255),
 ADD CONSTRAINT companies_jurisdiction_length CHECK(jurisdiction IS NULL OR length(jurisdiction) = 2),
 ADD CONSTRAINT companies_website_length CHECK(website IS NULL OR length(website) BETWEEN 1 AND 255);
CREATE INDEX companies_parent_idx ON companies(parent_id);
CREATE INDEX companies_parent_status_idx ON companies(parent_id, status);
CREATE INDEX companies_status_idx ON companies(status);
CREATE INDEX companies_legal_entity_type_idx ON companies(legal_entity_type_id);
CREATE INDEX companies_created_at_idx ON companies(created_at);

-- Demo and imported rows were inserted with explicit ids, which never advance
-- the identity: the next generated id must follow the highest existing one.
SELECT setval(pg_get_serial_sequence('companies','id'), GREATEST((SELECT max(id) FROM companies), 1), (SELECT max(id) IS NOT NULL FROM companies));

-- Tenant-owned postal addresses (Bilimbi `core/address`). Bilimbi's quoted
-- camelCase columns ("admin1Code", "rawInput", ...) are snake_case here, and
-- timestamps are timestamptz like every other Bilibi table.
-- Country and division point at Geonames, which is empty on install: an
-- address has no country until an operator imports countries.
CREATE TABLE addresses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES tenants(id),
    label text CHECK (label IS NULL OR length(btrim(label)) BETWEEN 1 AND 255),
    phone text CHECK (phone IS NULL OR length(btrim(phone)) BETWEEN 1 AND 255),
    line1 text CHECK (line1 IS NULL OR length(btrim(line1)) BETWEEN 1 AND 1000),
    line2 text CHECK (line2 IS NULL OR length(btrim(line2)) BETWEEN 1 AND 1000),
    line3 text CHECK (line3 IS NULL OR length(btrim(line3)) BETWEEN 1 AND 1000),
    locality text CHECK (locality IS NULL OR length(btrim(locality)) BETWEEN 1 AND 255),
    postcode text CHECK (postcode IS NULL OR length(btrim(postcode)) BETWEEN 1 AND 255),
    country_iso text CHECK (country_iso ~ '^[A-Z]{2}$')
        CONSTRAINT addresses_country_iso_foreign REFERENCES geonames_countries(iso) ON DELETE SET NULL,
    admin1_code text CHECK (length(admin1_code) BETWEEN 1 AND 20)
        CONSTRAINT addresses_admin1_code_foreign REFERENCES geonames_admin1(code) ON DELETE SET NULL,
    raw_input text CHECK (raw_input IS NULL OR length(raw_input) BETWEEN 1 AND 10000),
    source text CHECK (source IS NULL OR length(btrim(source)) BETWEEN 1 AND 255),
    source_ref text CHECK (source_ref IS NULL OR length(btrim(source_ref)) BETWEEN 1 AND 255),
    parser_version text CHECK (parser_version IS NULL OR length(btrim(parser_version)) BETWEEN 1 AND 255),
    parse_confidence numeric(5,4) CHECK (parse_confidence BETWEEN 0 AND 1),
    verification_status text NOT NULL DEFAULT 'unverified'
        CHECK (verification_status IN ('unverified', 'suggested', 'verified')),
    version bigint NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    -- The owner checks that a division belongs to the address's country; no
    -- CHECK here, so a Geonames delete can still null either reference.
    UNIQUE (tenant_id, id)
);
CREATE INDEX addresses_tenant ON addresses (tenant_id, id) WHERE deleted_at IS NULL;
CREATE INDEX addresses_country_iso ON addresses (country_iso);
CREATE INDEX addresses_admin1_code ON addresses (admin1_code);

-- Bilimbi's polymorphic `addressables(addressable_type, addressable_id)` is
-- replaced by one scoped foreign key per party kind (the K0 contract): an
-- attachment names exactly one Organisation or one Person of its own tenant.
CREATE TABLE address_attachments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES tenants(id),
    address_id bigint NOT NULL,
    organisation_id bigint,
    person_id bigint,
    kinds text[] NOT NULL DEFAULT '{}'
        CHECK (kinds <@ ARRAY['headquarters', 'billing', 'shipping', 'branch', 'other']::text[]),
    is_primary boolean NOT NULL DEFAULT false,
    priority smallint NOT NULL DEFAULT 0 CHECK (priority BETWEEN 0 AND 32767),
    valid_from date CHECK (valid_from BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
    valid_to date CHECK (valid_to BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
    version bigint NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, id),
    FOREIGN KEY (tenant_id, address_id) REFERENCES addresses(tenant_id, id),
    FOREIGN KEY (tenant_id, organisation_id) REFERENCES companies(tenant_id, id),
    FOREIGN KEY (tenant_id, person_id) REFERENCES persons(tenant_id, id),
    CHECK (num_nonnulls(organisation_id, person_id) = 1),
    CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_from <= valid_to)
);
-- One link per address and owner; its kinds, primary flag, priority and dates
-- describe how that owner uses the address.
CREATE UNIQUE INDEX address_attachments_organisation_unique
    ON address_attachments (tenant_id, organisation_id, address_id) WHERE organisation_id IS NOT NULL;
CREATE UNIQUE INDEX address_attachments_person_unique
    ON address_attachments (tenant_id, person_id, address_id) WHERE person_id IS NOT NULL;
CREATE INDEX address_attachments_address ON address_attachments (tenant_id, address_id);

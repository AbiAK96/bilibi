CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id), name text NOT NULL,
 email text NOT NULL, password_hash text NOT NULL,
 status text NOT NULL DEFAULT 'active', deleted_at timestamptz,
 UNIQUE(tenant_id,id), UNIQUE(tenant_id,email)
);
ALTER TABLE sessions ADD CONSTRAINT sessions_scoped_user_fk FOREIGN KEY(tenant_id,user_id) REFERENCES users(tenant_id,id);
ALTER TABLE principal_roles ADD CONSTRAINT principal_roles_scoped_user_fk FOREIGN KEY(tenant_id,user_id) REFERENCES users(tenant_id,id);
ALTER TABLE principal_capabilities ADD CONSTRAINT principal_capabilities_scoped_user_fk FOREIGN KEY(tenant_id,user_id) REFERENCES users(tenant_id,id);
CREATE TABLE notifications (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, user_id bigint NOT NULL, message text NOT NULL,
 read_at timestamptz, created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,user_id) REFERENCES users(tenant_id,id)
);
CREATE INDEX notifications_unread_idx ON notifications(tenant_id,user_id) WHERE read_at IS NULL;
